const SUPPORTED_LANGS = ["en", "es", "pt", "id"];

/** Normalise a subscriber's stored lang (which may be region-tagged, e.g.
 *  'es-MX' or 'pt-BR') to one of the four supported two-letter codes,
 *  defaulting to 'en' for anything unsupported. */
function normLang(lang) {
  const code = String(lang || "en").toLowerCase().slice(0, 2);
  return SUPPORTED_LANGS.includes(code) ? code : "en";
}

function getVerseSnippet(passage, lang) {
  const normalized = normLang(lang);
  const langSnippets = VERSE_SNIPPETS[normalized] || VERSE_SNIPPETS.en;
  return langSnippets[passage] || VERSE_SNIPPETS.en[passage] || DEFAULT_BODY[normalized] || DEFAULT_BODY.en;
}

function getTemplate(lang) {
  const normalized = normLang(lang);
  const langTemplates = TEMPLATES[normalized] || TEMPLATES.en;
  return langTemplates[Math.floor(Math.random() * langTemplates.length)];
}

